BEGIN;

CREATE TABLE gateways (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(150) NOT NULL,
    gateway_code VARCHAR(100) NOT NULL UNIQUE,
    manufacturer VARCHAR(120),
    model VARCHAR(120),
    firmware_version VARCHAR(80),
    status VARCHAR(30) NOT NULL DEFAULT 'offline',
    last_seen_at TIMESTAMPTZ,
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT gateways_status_valid CHECK (
        status IN ('online', 'offline', 'degraded', 'maintenance', 'disabled')
    )
);

CREATE TABLE devices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    gateway_id UUID REFERENCES gateways(id) ON DELETE SET NULL,
    system_id BIGINT REFERENCES systems(id) ON DELETE SET NULL,
    asset_id BIGINT REFERENCES assets(id) ON DELETE SET NULL,
    zone_id BIGINT REFERENCES zones(id) ON DELETE SET NULL,
    device_code VARCHAR(150) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    device_type VARCHAR(60) NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    protocol VARCHAR(30) NOT NULL,
    manufacturer VARCHAR(120),
    model VARCHAR(120),
    serial_number VARCHAR(150),
    external_identifier VARCHAR(200),
    status VARCHAR(30) NOT NULL DEFAULT 'inactive',
    credential_reference VARCHAR(300),
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_seen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT devices_source_valid CHECK (
        source_type IN ('iot', 'bms')
    ),
    CONSTRAINT devices_protocol_valid CHECK (
        protocol IN (
            'mqtt', 'modbus_tcp', 'modbus_rtu',
            'bacnet_ip', 'bacnet_mstp', 'opc_ua',
            'http_api', 'other'
        )
    ),
    CONSTRAINT devices_status_valid CHECK (
        status IN ('active', 'inactive', 'offline', 'fault', 'maintenance', 'disabled')
    )
);

CREATE TABLE data_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_code VARCHAR(200) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    measurement_type VARCHAR(60) NOT NULL,
    data_type VARCHAR(20) NOT NULL DEFAULT 'numeric',
    unit VARCHAR(40),
    unit_symbol VARCHAR(20),
    expected_interval_seconds INTEGER,
    min_expected_value DOUBLE PRECISION,
    max_expected_value DOUBLE PRECISION,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT data_points_type_valid CHECK (
        data_type IN ('numeric', 'boolean', 'string', 'json')
    ),
    CONSTRAINT data_points_interval_positive CHECK (
        expected_interval_seconds IS NULL OR expected_interval_seconds > 0
    ),
    CONSTRAINT data_points_range_valid CHECK (
        min_expected_value IS NULL
        OR max_expected_value IS NULL
        OR min_expected_value <= max_expected_value
    )
);

CREATE TABLE device_data_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    data_point_id BIGINT NOT NULL REFERENCES data_points(id) ON DELETE RESTRICT,
    external_point_id VARCHAR(200),
    acquisition_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sampling_interval_seconds INTEGER,
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT device_data_points_unique UNIQUE (device_id, data_point_id),
    CONSTRAINT device_data_points_interval_positive CHECK (
        sampling_interval_seconds IS NULL OR sampling_interval_seconds > 0
    )
);

CREATE TABLE ingestion_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE RESTRICT,
    gateway_id UUID REFERENCES gateways(id) ON DELETE SET NULL,
    source_type VARCHAR(20) NOT NULL,
    external_event_id VARCHAR(200),
    payload_hash VARCHAR(128),
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    measured_at TIMESTAMPTZ,
    processing_status VARCHAR(20) NOT NULL DEFAULT 'received',
    error_message TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ingestion_events_source_valid CHECK (
        source_type IN ('iot', 'bms')
    ),
    CONSTRAINT ingestion_events_status_valid CHECK (
        processing_status IN ('received', 'processed', 'rejected', 'failed')
    )
);

CREATE UNIQUE INDEX idx_ingestion_external_event
    ON ingestion_events (device_id, external_event_id)
    WHERE external_event_id IS NOT NULL;

CREATE INDEX idx_devices_gateway ON devices(gateway_id);
CREATE INDEX idx_devices_system ON devices(system_id);
CREATE INDEX idx_devices_asset ON devices(asset_id);
CREATE INDEX idx_devices_zone ON devices(zone_id);
CREATE INDEX idx_devices_source ON devices(source_type);
CREATE INDEX idx_device_data_points_device ON device_data_points(device_id);
CREATE INDEX idx_device_data_points_point ON device_data_points(data_point_id);
CREATE INDEX idx_ingestion_device_received ON ingestion_events(device_id, received_at DESC);
CREATE INDEX idx_ingestion_status ON ingestion_events(processing_status);

COMMIT;
