BEGIN;

CREATE TABLE building (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    address VARCHAR(300),
    city VARCHAR(120),
    country_code CHAR(2),
    building_type VARCHAR(50) NOT NULL,
    area_sqm NUMERIC(12,2),
    construction_year SMALLINT,
    energy_class VARCHAR(10),
    occupancy_type VARCHAR(50),
    latitude NUMERIC(10,7),
    longitude NUMERIC(10,7),
    timezone VARCHAR(64) NOT NULL DEFAULT 'Europe/Rome',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT building_single_installation CHECK (id = 1),
    CONSTRAINT building_area_positive CHECK (area_sqm IS NULL OR area_sqm > 0),
    CONSTRAINT building_latitude_valid CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT building_longitude_valid CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE TABLE floors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    floor_number SMALLINT NOT NULL,
    description TEXT,
    area_sqm NUMERIC(12,2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT floors_area_positive CHECK (area_sqm IS NULL OR area_sqm > 0),
    CONSTRAINT floors_number_unique UNIQUE (floor_number)
);

CREATE TABLE zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id BIGINT REFERENCES floors(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    zone_type VARCHAR(50) NOT NULL,
    area_sqm NUMERIC(12,2),
    description TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT zones_area_positive CHECK (area_sqm IS NULL OR area_sqm > 0)
);

CREATE TABLE systems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT REFERENCES zones(id) ON DELETE SET NULL,
    name VARCHAR(200) NOT NULL,
    category VARCHAR(80) NOT NULL,
    manufacturer VARCHAR(120),
    model VARCHAR(120),
    serial_number VARCHAR(120),
    installation_date DATE,
    commissioning_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'active',
    description TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT systems_status_valid CHECK (
        status IN ('active', 'inactive', 'maintenance', 'decommissioned')
    )
);

CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id BIGINT NOT NULL REFERENCES systems(id) ON DELETE RESTRICT,
    zone_id BIGINT REFERENCES zones(id) ON DELETE SET NULL,
    parent_asset_id BIGINT,
    name VARCHAR(200) NOT NULL,
    asset_type VARCHAR(80) NOT NULL,
    manufacturer VARCHAR(120),
    model VARCHAR(120),
    serial_number VARCHAR(120),
    installation_date DATE,
    warranty_expiry DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'active',
    criticality VARCHAR(20) NOT NULL DEFAULT 'medium',
    description TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT assets_status_valid CHECK (
        status IN ('active', 'inactive', 'maintenance', 'decommissioned')
    ),
    CONSTRAINT assets_criticality_valid CHECK (
        criticality IN ('low', 'medium', 'high', 'critical')
    ),
    CONSTRAINT assets_not_own_parent CHECK (
        parent_asset_id IS NULL OR parent_asset_id <> id
    ),
    CONSTRAINT assets_id_system_unique UNIQUE (id, system_id),
    CONSTRAINT assets_parent_same_system FOREIGN KEY (parent_asset_id, system_id)
        REFERENCES assets(id, system_id) ON DELETE RESTRICT
);

CREATE FUNCTION prevent_asset_hierarchy_cycles()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.parent_asset_id IS NOT NULL THEN
        IF EXISTS (
            WITH RECURSIVE ancestors(id, parent_asset_id) AS (
                SELECT id, parent_asset_id
                FROM assets
                WHERE id = NEW.parent_asset_id

                UNION ALL

                SELECT a.id, a.parent_asset_id
                FROM assets a
                JOIN ancestors p ON a.id = p.parent_asset_id
            )
            SELECT 1 FROM ancestors WHERE id = NEW.id
        ) THEN
            RAISE EXCEPTION 'Asset hierarchy cycle detected';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prevent_asset_hierarchy_cycles
BEFORE INSERT OR UPDATE OF parent_asset_id, system_id
ON assets
FOR EACH ROW
EXECUTE FUNCTION prevent_asset_hierarchy_cycles();

CREATE INDEX idx_zones_floor ON zones(floor_id);
CREATE INDEX idx_systems_zone ON systems(zone_id);
CREATE INDEX idx_systems_category ON systems(category);
CREATE INDEX idx_assets_system ON assets(system_id);
CREATE INDEX idx_assets_zone ON assets(zone_id);
CREATE INDEX idx_assets_parent ON assets(parent_asset_id);
CREATE INDEX idx_assets_status ON assets(status);

COMMIT;
