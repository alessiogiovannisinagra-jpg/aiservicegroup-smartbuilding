BEGIN;

-- Consente di verificare che ogni evento appartenga
-- allo stesso dispositivo associato alla misurazione.
ALTER TABLE ingestion_events
    ADD CONSTRAINT ingestion_events_event_device_unique
    UNIQUE (event_id, device_id);

CREATE TABLE telemetry_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    measured_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    event_id UUID NOT NULL,
    device_id UUID NOT NULL,
    data_point_id BIGINT NOT NULL,

    value_type VARCHAR(20) NOT NULL,
    value_numeric DOUBLE PRECISION,
    value_boolean BOOLEAN,
    value_text TEXT,
    value_json JSONB,

    quality VARCHAR(20) NOT NULL DEFAULT 'valid',
    unit VARCHAR(40),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT telemetry_readings_pk
        PRIMARY KEY (measured_at, id),

    CONSTRAINT telemetry_readings_event_device_fk
        FOREIGN KEY (event_id, device_id)
        REFERENCES ingestion_events(event_id, device_id)
        ON DELETE RESTRICT,

    CONSTRAINT telemetry_readings_device_point_fk
        FOREIGN KEY (device_id, data_point_id)
        REFERENCES device_data_points(device_id, data_point_id)
        ON DELETE RESTRICT,

    CONSTRAINT telemetry_readings_value_type_valid
        CHECK (value_type IN ('numeric', 'boolean', 'string', 'json')),

    CONSTRAINT telemetry_readings_value_consistent
        CHECK (
            (value_type = 'numeric'
                AND value_numeric IS NOT NULL
                AND value_boolean IS NULL
                AND value_text IS NULL
                AND value_json IS NULL)
            OR
            (value_type = 'boolean'
                AND value_numeric IS NULL
                AND value_boolean IS NOT NULL
                AND value_text IS NULL
                AND value_json IS NULL)
            OR
            (value_type = 'string'
                AND value_numeric IS NULL
                AND value_boolean IS NULL
                AND value_text IS NOT NULL
                AND value_json IS NULL)
            OR
            (value_type = 'json'
                AND value_numeric IS NULL
                AND value_boolean IS NULL
                AND value_text IS NULL
                AND value_json IS NOT NULL)
        ),

    CONSTRAINT telemetry_readings_quality_valid
        CHECK (quality IN ('valid', 'estimated', 'incomplete', 'invalid'))
);

-- Verifica la corrispondenza tra tipo dichiarato
-- nel punto di misura e tipo effettivamente acquisito.
CREATE FUNCTION validate_telemetry_value_type()
RETURNS TRIGGER AS $$
DECLARE
    expected_type VARCHAR(20);
BEGIN
    SELECT data_type
    INTO expected_type
    FROM data_points
    WHERE id = NEW.data_point_id;

    IF expected_type IS DISTINCT FROM NEW.value_type THEN
        RAISE EXCEPTION
            'Telemetry value type mismatch: expected %, received %',
            expected_type, NEW.value_type;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_telemetry_value_type
BEFORE INSERT OR UPDATE OF data_point_id, value_type
ON telemetry_readings
FOR EACH ROW
EXECUTE FUNCTION validate_telemetry_value_type();

-- Registro permanente di deduplicazione evento-punto.
CREATE TABLE telemetry_event_points (
    event_id UUID NOT NULL
        REFERENCES ingestion_events(event_id) ON DELETE RESTRICT,
    data_point_id BIGINT NOT NULL
        REFERENCES data_points(id) ON DELETE RESTRICT,
    measured_at TIMESTAMPTZ NOT NULL,
    registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT telemetry_event_points_pk
        PRIMARY KEY (event_id, data_point_id)
);

-- Ogni misurazione registra atomicamente la propria chiave
-- di deduplicazione. Un duplicato annulla l'intera transazione.
CREATE FUNCTION register_telemetry_event_point()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO telemetry_event_points (
        event_id, data_point_id, measured_at
    )
    VALUES (
        NEW.event_id, NEW.data_point_id, NEW.measured_at
    );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_register_telemetry_event_point
AFTER INSERT ON telemetry_readings
FOR EACH ROW
EXECUTE FUNCTION register_telemetry_event_point();

CREATE INDEX idx_telemetry_device_time
    ON telemetry_readings(device_id, measured_at DESC);

CREATE INDEX idx_telemetry_point_time
    ON telemetry_readings(data_point_id, measured_at DESC);

CREATE INDEX idx_telemetry_quality_time
    ON telemetry_readings(quality, measured_at DESC);

-- Conversione in hypertable TimescaleDB.
SELECT create_hypertable(
    'telemetry_readings',
    'measured_at',
    chunk_time_interval => INTERVAL '7 days',
    if_not_exists => TRUE
);

COMMIT;
